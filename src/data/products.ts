export function getProductBySlug(slug: string): Product | undefined {
  return PRODUCTS.find((p) => p.slug === slug);
}

export function getFeaturedProducts(): Product[] {
  return PRODUCTS.filter((p) => p.isFeatured).sort((a, b) => a.displayOrder - b.displayOrder);
}

export function getProductsByCategory(category: string): Product[] {
  if (category === "All Products" || !category) {
    return PRODUCTS.sort((a, b) => a.displayOrder - b.displayOrder);
  }
  return PRODUCTS.filter(
    (p) => p.category === category || p.secondaryCategories?.includes(category as ProductCategory)
  ).sort((a, b) => a.displayOrder - b.displayOrder);
}
